// All telemetry tuning lives in this block. The row format and its longest
// line live in MovementTelemetryFormat.h, which the harness shares.
#define MOVEMENT_TELEMETRY_FILE		"movement-telemetry.csv"
#define MOVEMENT_TELEMETRY_FLUSH_MS	250	// writer wake and flush period
#define MOVEMENT_TELEMETRY_BACKLOG	(64*1024)	// backlog cap, bytes
#define MOVEMENT_TELEMETRY_JUMP		1	// the jump of phase 0: the air extensions count from 2

// The readout: the DebugMenu page (re3.cpp) and the VarConsole rows show these,
// and Tick refreshes them from the snapshot. They live with the module that
// fills them, the way the drift readout lives with the drift layer.
int32 gMovementDebugState;	// eMoveStateId
int32 gMovementDebugStance;	// eStance
int32 gMovementDebugTier;	// eMoveTier
float gMovementDebugSpeed;	// units per second
float gMovementDebugTarget;	// units per second
uint32 gMovementDebugRows;	// rows appended to the file
uint32 gMovementDebugDropped;	// rows dropped on a full backlog

// The two sides of the telemetry meet in one block: the game thread fills the
// backlog, the writer thread owns the file and drains it. The backlog is one
// fixed buffer, so a row never allocates; a row that does not fit is dropped
// and counted. The block is allocated once and deliberately leaked; a static
// destructor would have to race the exit handler and the writer thread.
struct tMovementTelemetry
{
	std::mutex mutex;
	std::condition_variable cv;
	std::thread writer;
	char backlog[MOVEMENT_TELEMETRY_BACKLOG];
	size_t nBacklog;	// bytes in the backlog
	uint32 nDropped;	// rows dropped on overflow, written out as a comment
	uint32 nRows;		// rows appended, the readout's counter (game thread only)
	uint32 nDroppedTotal;	// the same drops, kept for the readout (game thread only)
	uint32 nStep;		// the solver step of the rows being written
	bool bTerminate;
	bool bDisabled;	// no file: drop the rows and do not count them
	bool bFirstCall;	// no previous state to compare the state edges against
	eMoveStateId ePrevState;
};

static tMovementTelemetry *ms_pTelemetry;

static tMovementTelemetry *MovementTelemetryInit(void);

// The build revision is generated by the build (see extras/GitSHA1.h).
static const char *
MovementTelemetryRevision(void)
{
#ifdef USE_OUR_VERSIONING
	return g_GIT_SHA1;
#else
	return "unknown";
#endif
}

// The read-only rows of the in-game console (VarConsole.h). They show the live
// movement state; Tick refreshes the mirror every frame, so an edit the console
// makes is gone with the next frame. They arrive with the first debug frame,
// the lazy moment the file does.
static void
MovementTelemetryAddConsoleRows(void)
{
	VarConsole.Add("Movement state", &gMovementDebugState, 1, 0, MOVE_NUMSTATES-1, true);
	VarConsole.Add("Movement stance", &gMovementDebugStance, 1, 0, STANCE_NUM-1, true);
	VarConsole.Add("Movement tier", &gMovementDebugTier, 1, 0, TIER_NUM-1, true);
	VarConsole.Add("Movement speed", &gMovementDebugSpeed, 0.1f, 0.0f, 100.0f, true);
	VarConsole.Add("Movement target", &gMovementDebugTarget, 0.1f, 0.0f, 100.0f, true);
	VarConsole.Add("Movement rows", &gMovementDebugRows, 1, 0, 1000000, true);
}

// The header block, one line at a time. The column order is fixed; every
// reader of the log depends on it. The row itself is one solver step: the
// snapshot columns, then the intent columns, then the event token
// (MovementTelemetryFormat.h).
static std::string
MovementTelemetryHeaders(void)
{
	char line[MOVEMENT_TELEMETRY_MAX_ROW];
	std::string headers;
	time_t now = time(nil);
	struct tm *local = localtime(&now);

	headers += "# reVC movement telemetry\n";
	sprintf(line, "# build %s\n", MovementTelemetryRevision());
	headers += line;
	if(local != nil){
		strftime(line, sizeof(line), "# session %Y-%m-%d %H:%M:%S\n", local);
		headers += line;
	}
	headers += "# speed and target are units per second, spin and slope degrees, surface an eSurfaceType\n";
	headers += "# fwd and side are the input direction in the body frame: +1 is forward, +1 is right\n";
	headers += "# contacts is the eMoveContact mask: 1 ground, 2 wall, 4 head\n";
	headers += "# flags is the intent mask: 1 onGround, 2 steepCliff, 4 hasInput, 8 jump, 16 dive,\n";
	headers += "#   32 crouch, 64 sprint, 128 exitVehicle, 256 headroomClear, 512 prone\n";
	headers += "# the intent velocities and speeds are engine units, one unit per 1/50 second\n";
	headers += "# dt is seconds; heading, facing and the slope normal are radians\n";
	headers += "# one row is one solver step; the edge rows of a step share its step number\n";
	headers += MOVEMENT_TELEMETRY_COLUMNS "\n";
	return headers;
}

// The game changes its working directory during play (loading, replay saves),
// so the file is resolved against the directory the game started in, not
// against whatever the directory is when the first movement frame runs.
static std::string
MovementTelemetryFilePath(void)
{
	char cwd[512];

	if(MovementTelemetryGetCwd(cwd, sizeof(cwd)) != nil){
		std::string path(cwd);
		if(!path.empty() && path[path.size()-1] != '/' && path[path.size()-1] != '\\')
			path += '/';
		path += MOVEMENT_TELEMETRY_FILE;
		return path;
	}
	return MOVEMENT_TELEMETRY_FILE;
}

// Appends one finished line to the backlog. This is the only place the game
// thread touches the shared state, and it never touches the file.
static void
MovementTelemetryAppend(const char *line)
{
	tMovementTelemetry *state = ms_pTelemetry;
	size_t length = strlen(line);

	std::lock_guard<std::mutex> lock(state->mutex);
	if(state->bDisabled)
		return;
	if(state->nBacklog + length + 1 > MOVEMENT_TELEMETRY_BACKLOG){
		// The writer cannot keep up. Drop the row and count it; the writer
		// writes the count back as a comment line.
		state->nDropped++;
		state->nDroppedTotal++;
		return;
	}
	memcpy(state->backlog + state->nBacklog, line, length);
	state->nBacklog += length;
	state->backlog[state->nBacklog++] = '\n';
	state->nRows++;
	// Wake the writer early only when the backlog has grown far past one
	// flush period, so the game thread stays cheap in normal play.
	if(state->nBacklog > MOVEMENT_TELEMETRY_BACKLOG/2)
		state->cv.notify_one();
}

// Writes one row of the passed step, with the event token when there is one.
// The values are the solver's snapshot and the intent the step consumed, the
// same ones the on-screen readout shows, so the row and the readout cannot
// disagree.
static void
MovementTelemetryRow(const SMoveIntent &intent, const SMoveSnapshot &snap, const char *event)
{
	tMovementTelemetry *state = ms_pTelemetry;
	char line[MOVEMENT_TELEMETRY_MAX_ROW];

	if(state == nil)
		return;

	MoveTelemetryFormatRow(line, sizeof(line),
		(uint32)CTimer::GetTimeInMilliseconds(), state->nStep, intent, snap, event);
	MovementTelemetryAppend(line);
}

// The token of one event bit (see eMoveEvent). A jump carries its index once
// the air extensions report one: the second jump of the double jump writes
// JUMP2. The solver of phase 0 reports the plain jump, whose token is JUMP.
static void
MovementTelemetryEventToken(uint32 event, int jump, char *token)
{
	switch(event){
	case EVENT_LANDED:
		strcpy(token, "LAND");
		break;
	case EVENT_JUMP:
		if(jump > 1)
			sprintf(token, "JUMP%d", jump);
		else
			strcpy(token, "JUMP");
		break;
	case EVENT_HEAD_HIT:
		strcpy(token, "HIT_HEAD");
		break;
	case EVENT_WALL_CONTACT:
		strcpy(token, "WALL_CONTACT");
		break;
	case EVENT_WALL_LEFT:
		strcpy(token, "WALL_LEFT");
		break;
	default:
		token[0] = '\0';
		break;
	}
}

// The writer thread owns the file. It wakes on the condition variable at most
// every 250 ms, takes the backlog out under the lock, then writes and flushes
// it outside the lock, so the game thread never waits on the disk.
static void
MovementTelemetryWriter(tMovementTelemetry *state, std::string headers, std::string path)
{
	FILE *file = fopen(path.c_str(), "w");
	if(file == nil){
		// No file: turn the game thread off instead of filling a backlog
		// that nobody drains. With no file there is nowhere to note dropped
		// rows, so the reason goes to the debug output.
		fprintf(stderr, "movement telemetry: cannot open %s, telemetry off\n", path.c_str());
		std::lock_guard<std::mutex> lock(state->mutex);
		state->bDisabled = true;
		state->nBacklog = 0;
		return;
	}

	fwrite(headers.data(), 1, headers.size(), file);

	for(;;){
		std::string chunk;
		uint32 dropped;
		bool done;

		{
			std::unique_lock<std::mutex> lock(state->mutex);
			state->cv.wait_for(lock, std::chrono::milliseconds(MOVEMENT_TELEMETRY_FLUSH_MS),
				[state]{ return state->bTerminate || state->nBacklog > 0; });
			// The backlog is one fixed buffer, so the writer takes the live
			// part of it to write outside the lock.
			chunk.assign(state->backlog, state->nBacklog);
			state->nBacklog = 0;
			dropped = state->nDropped;
			state->nDropped = 0;
			done = state->bTerminate && chunk.empty();
		}

		if(dropped > 0){
			char line[48];
			int length = sprintf(line, "# DROPPED %u lines\n", dropped);
			fwrite(line, 1, length, file);
		}
		if(!chunk.empty())
			fwrite(chunk.data(), 1, chunk.size(), file);
		if(dropped > 0 || !chunk.empty())
			fflush(file);
		if(done)
			break;
	}

	fclose(file);
}

// Stops the writer at a normal process exit (an assert aborts through _exit
// and skips this, losing the last rows). The writer drains the backlog,
// flushes and closes the file before it returns, so this side only waits.
static void
MovementTelemetryShutdown(void)
{
	tMovementTelemetry *state = ms_pTelemetry;

	if(state == nil)
		return;

	{
		std::lock_guard<std::mutex> lock(state->mutex);
		state->bTerminate = true;
	}
	state->cv.notify_one();
	if(state->writer.joinable())
		state->writer.join();
}

// The lazy init runs on the game thread, but the thread it starts opens the
// file, so the frame itself still does no file work.
static tMovementTelemetry *
MovementTelemetryInit(void)
{
	tMovementTelemetry *state = new tMovementTelemetry;

	state->nBacklog = 0;
	state->nDropped = 0;
	state->nRows = 0;
	state->nDroppedTotal = 0;
	state->nStep = 0;
	state->bTerminate = false;
	state->bDisabled = false;
	state->bFirstCall = true;
	state->ePrevState = MOVE_GROUND;

	ms_pTelemetry = state;
	MovementTelemetryAddConsoleRows();
	atexit(MovementTelemetryShutdown);
	state->writer = std::thread(MovementTelemetryWriter, state, MovementTelemetryHeaders(), MovementTelemetryFilePath());
	return state;
}

void
CMovementTelemetry::Tick(const SMoveIntent &intent, const SMoveSnapshot &snap)
{
	static const uint32 events[] = {
		EVENT_LANDED, EVENT_JUMP, EVENT_HEAD_HIT, EVENT_WALL_CONTACT, EVENT_WALL_LEFT
	};
	tMovementTelemetry *state;
	char token[32];
	int i;

	if(!gMovementDebug)
		return;

	state = ms_pTelemetry;
	if(state == nil)
		state = MovementTelemetryInit();

	// One Tick is one solver step, and every row of the step carries its
	// number: the edge rows below and the live row.
	state->nStep++;

	// The readout: the DebugMenu page (re3.cpp) and the console rows. The two
	// counters are the game thread's own, so they need no lock.
	gMovementDebugState = snap.state;
	gMovementDebugStance = snap.stance;
	gMovementDebugTier = snap.tier;
	gMovementDebugSpeed = snap.speed*MOVE_ENGINE_UNITS_PER_SECOND;
	gMovementDebugTarget = snap.targetSpeed*MOVE_ENGINE_UNITS_PER_SECOND;
	gMovementDebugRows = state->nRows;
	gMovementDebugDropped = state->nDroppedTotal;

	if(!state->bFirstCall){
		// A state change writes the exit row of the state the step left and
		// the enter row of the state it took. Both carry the new state's
		// values: the row is written at the change, and the token names the
		// side of it.
		if(state->ePrevState != snap.state){
			sprintf(token, "EXIT_%s", CPlayerMoveSolver::GetStateName(state->ePrevState));
			MovementTelemetryRow(intent, snap, token);
			sprintf(token, "ENTER_%s", CPlayerMoveSolver::GetStateName(snap.state));
			MovementTelemetryRow(intent, snap, token);
		}
		// One row per event bit the step reports, in the order the rows list
		// them above.
		for(i = 0; i < ARRAY_SIZE(events); i++){
			if((snap.events & events[i]) == 0)
				continue;
			MovementTelemetryEventToken(events[i], MOVEMENT_TELEMETRY_JUMP, token);
			MovementTelemetryRow(intent, snap, token);
		}
	}
	state->bFirstCall = false;
	state->ePrevState = snap.state;

	// The live row of every step: the session is a regression stream, so no
	// step may be missing from the file. The edge rows above share this row's
	// step number and snapshot.
	MovementTelemetryRow(intent, snap, "");
}
