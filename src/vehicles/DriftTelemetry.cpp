// All telemetry tuning lives in this block.
#define DRIFT_TELEMETRY_FILE		"drift-telemetry.csv"
#define DRIFT_TELEMETRY_ROW_MS		50	// game ms between two live rows
#define DRIFT_TELEMETRY_FLUSH_MS	250	// writer wake and flush period
#define DRIFT_TELEMETRY_BACKLOG		(128*1024)	// backlog cap, bytes
#define DRIFT_TELEMETRY_LINE		256	// one CSV row fits here
// DRIFT_TICK_RATE and DRIFT_ENTRY_STEER come from DriftControl.h.

// The two sides of the telemetry meet in one block: the game thread fills the
// backlog, the writer thread owns the file and drains it. The block is
// allocated once and deliberately leaked; a static destructor would have to
// race the exit handler and the writer thread.
struct tDriftTelemetry
{
	std::mutex mutex;
	std::condition_variable cv;
	std::thread writer;
	std::string backlog;
	uint32 nDropped;	// rows dropped on overflow, written out as a comment
	uint32 nNextRowMs;	// game ms when the next live row is due
	bool bTerminate;
	bool bDisabled;		// no file: drop the rows and do not count them
	bool bFirstCall;	// no previous state to compare edges against yet
	CDriftControl::eDriftPhase ePrevPhase;
	bool bPrevAir;
	bool bPrevHandbrake;
	float fPrevBoost;
};

static tDriftTelemetry *ms_pTelemetry;

static tDriftTelemetry *DriftTelemetryInit(CAutomobile *car, CDriftControl *ctrl);

// The build revision is generated by the build (see extras/GitSHA1.h).
static const char *
DriftTelemetryRevision(void)
{
#ifdef USE_OUR_VERSIONING
	return g_GIT_SHA1;
#else
	return "unknown";
#endif
}

// The header block, one line at a time. The column order is fixed; every
// reader of the log depends on it.
static std::string
DriftTelemetryHeaders(void)
{
	char line[DRIFT_TELEMETRY_LINE];
	std::string headers;
	time_t now = time(nil);
	struct tm *local = localtime(&now);

	headers += "# reVC drift telemetry\n";
	sprintf(line, "# build %s\n", DriftTelemetryRevision());
	headers += line;
	if(local != nil){
		strftime(line, sizeof(line), "# session %Y-%m-%d %H:%M:%S\n", local);
		headers += line;
	}
	sprintf(line, "# drift enabled=%d strength=%.2f assist=%.2f\n",
		gDriftEnabled ? 1 : 0, gDriftStrength, gDriftAssist);
	headers += line;
	headers += "ms,phase,turn,ground,handbrake,steer,kph,frac,slip,target,yaw,grip_cut,grip_scale,charge,boost,event\n";
	return headers;
}

// The game changes its working directory during play (loading, replay saves),
// so the file is resolved against the directory the game started in, not
// against whatever the directory is when the first drift runs.
static std::string
DriftTelemetryFilePath(void)
{
	char cwd[512];

	if(DriftTelemetryGetCwd(cwd, sizeof(cwd)) != nil){
		std::string path(cwd);
		if(!path.empty() && path[path.size()-1] != '/' && path[path.size()-1] != '\\')
			path += '/';
		path += DRIFT_TELEMETRY_FILE;
		return path;
	}
	return DRIFT_TELEMETRY_FILE;
}

// Appends one finished line to the backlog. This is the only place the game
// thread touches the shared state, and it never touches the file.
static void
DriftTelemetryAppend(const char *line)
{
	tDriftTelemetry *state = ms_pTelemetry;
	size_t length = strlen(line);

	std::lock_guard<std::mutex> lock(state->mutex);
	if(state->bDisabled)
		return;
	if(state->backlog.size() + length + 1 > DRIFT_TELEMETRY_BACKLOG){
		// The writer cannot keep up. Drop the row and count it; the writer
		// writes the count back as a comment line.
		state->nDropped++;
		return;
	}
	state->backlog.append(line, length);
	state->backlog += '\n';
	// Wake the writer early only when the backlog has grown far past one
	// flush period, so the game thread stays cheap in normal play.
	if(state->backlog.size() > DRIFT_TELEMETRY_BACKLOG/2)
		state->cv.notify_one();
}

// Formats one CSV row into the stack buffer, then appends it.
static void
DriftTelemetryFormat(const char *format, ...)
{
	char line[DRIFT_TELEMETRY_LINE];
	va_list args;

	va_start(args, format);
	vsnprintf(line, sizeof(line), format, args);
	va_end(args);

	DriftTelemetryAppend(line);
}

// Writes one row of the current state, with the event token when there is one.
// The angles come from the model's accessors, the same ones the on-screen
// readout uses (see DriftControl.cpp).
static void
DriftTelemetryRow(CAutomobile *car, CDriftControl *ctrl, const char *event)
{
	tDriftTelemetry *state = ms_pTelemetry;
	float fMaxVelocity;
	float fSpeed;

	if(state == nil)
		return;

	fMaxVelocity = car->pHandling->Transmission.fMaxVelocity;
	fSpeed = car->m_vecMoveSpeed.Magnitude();

	DriftTelemetryFormat("%u,%s,%d,%d,%d,%.3f,%.1f,%.3f,%.1f,%.1f,%.1f,%.2f,%.3f,%.2f,%.3f,%s",
		(uint32)CTimer::GetTimeInMilliseconds(),
		CDriftControl::GetPhaseName(ctrl->m_Phase),
		ctrl->m_bHandbrakeTurn ? 1 : 0,
		car->m_nWheelsOnGround >= 2 ? 1 : 0,
		car->bIsHandbrakeOn ? 1 : 0,
		car->m_fSteerInput,
		fSpeed*3.6f,
		fSpeed/fMaxVelocity,
		ctrl->GetSlipAngleDeg(),
		ctrl->GetTargetSlipDeg(),
		ctrl->GetYawRateDeg(car),
		ctrl->m_fGripCut,
		ctrl->GetRearGripScale(),
		ctrl->m_fDriftTime,
		ctrl->m_fBoostLevel,
		event != nil ? event : "");

	state->nNextRowMs = (uint32)CTimer::GetTimeInMilliseconds() + DRIFT_TELEMETRY_ROW_MS;
}

// The writer thread owns the file. It wakes on the condition variable at most
// every 250 ms, takes the backlog out under the lock, then writes and flushes
// it outside the lock, so the game thread never waits on the disk.
static void
DriftTelemetryWriter(tDriftTelemetry *state, std::string headers, std::string path)
{
	FILE *file = fopen(path.c_str(), "w");
	if(file == nil){
		// No file: turn the game thread off instead of filling a backlog
		// that nobody drains. With no file there is nowhere to note dropped
		// rows, so the reason goes to the debug output.
		fprintf(stderr, "drift telemetry: cannot open %s, telemetry off\n", path.c_str());
		std::lock_guard<std::mutex> lock(state->mutex);
		state->bDisabled = true;
		state->backlog.clear();
		return;
	}

	fwrite(headers.data(), 1, headers.size(), file);

	for(;;){
		std::string chunk;
		uint32 dropped;
		bool done;

		{
			std::unique_lock<std::mutex> lock(state->mutex);
			state->cv.wait_for(lock, std::chrono::milliseconds(DRIFT_TELEMETRY_FLUSH_MS),
				[state]{ return state->bTerminate || !state->backlog.empty(); });
			chunk.swap(state->backlog);
			dropped = state->nDropped;
			state->nDropped = 0;
			done = state->bTerminate && chunk.empty();
		}

		if(dropped > 0){
			char line[48];
			int length = sprintf(line, "# DROPPED %u lines\n", dropped);
			fwrite(line, 1, length, file);
		}
		if(!chunk.empty())
			fwrite(chunk.data(), 1, chunk.size(), file);
		if(dropped > 0 || !chunk.empty())
			fflush(file);
		if(done)
			break;
	}

	fclose(file);
}

// Stops the writer at a normal process exit (an assert aborts through _exit
// and skips this, losing the last rows). The writer drains the backlog,
// flushes and closes the file before it returns, so this side only waits.
static void
DriftTelemetryShutdown(void)
{
	tDriftTelemetry *state = ms_pTelemetry;

	if(state == nil)
		return;

	{
		std::lock_guard<std::mutex> lock(state->mutex);
		state->bTerminate = true;
	}
	state->cv.notify_one();
	if(state->writer.joinable())
		state->writer.join();
}

// The lazy init runs on the game thread, but the thread it starts opens the
// file, so the frame itself still does no file work.
static tDriftTelemetry *
DriftTelemetryInit(CAutomobile *car, CDriftControl *ctrl)
{
	tDriftTelemetry *state = new tDriftTelemetry;

	state->nDropped = 0;
	state->nNextRowMs = 0;
	state->bTerminate = false;
	state->bDisabled = false;
	state->bFirstCall = true;
	state->ePrevPhase = ctrl->m_Phase;
	state->bPrevAir = car->m_nWheelsOnGround < 2;
	state->bPrevHandbrake = !!car->bIsHandbrakeOn;
	state->fPrevBoost = ctrl->m_fBoostLevel;

	ms_pTelemetry = state;
	atexit(DriftTelemetryShutdown);
	state->writer = std::thread(DriftTelemetryWriter, state, DriftTelemetryHeaders(), DriftTelemetryFilePath());
	return state;
}

void
CDriftTelemetry::Tick(CAutomobile *car, CDriftControl *ctrl)
{
	tDriftTelemetry *state;
	bool air;
	bool handbrake;

	if(!gDriftDebug || car == nil || ctrl == nil)
		return;

	state = ms_pTelemetry;
	if(state == nil)
		state = DriftTelemetryInit(car, ctrl);
	if(state == nil)
		return;

	air = car->m_nWheelsOnGround < 2;
	handbrake = !!car->bIsHandbrakeOn;

	if(!state->bFirstCall){
		// The edges come from the change since the previous call, so they are
		// compared before this frame's snapshot is stored.
		if(state->ePrevPhase != ctrl->m_Phase){
			if(state->ePrevPhase == CDriftControl::DRIFT_PHASE_INACTIVE &&
			   ctrl->m_Phase == CDriftControl::DRIFT_PHASE_ENGAGE)
				DriftTelemetryRow(car, ctrl, ctrl->m_bHandbrakeTurn ? "TURN" : "ENTER");
			else if(state->ePrevPhase == CDriftControl::DRIFT_PHASE_ENGAGE &&
			        ctrl->m_Phase == CDriftControl::DRIFT_PHASE_DRIFT)
				DriftTelemetryRow(car, ctrl, "RUN");
			else if(state->ePrevPhase == CDriftControl::DRIFT_PHASE_RECOVER &&
			        ctrl->m_Phase == CDriftControl::DRIFT_PHASE_INACTIVE)
				DriftTelemetryRow(car, ctrl, "END");
		}
		// The drift pauses in the air; the pause and the resume are edges
		// while a drift is on.
		if(air != state->bPrevAir && ctrl->m_Phase != CDriftControl::DRIFT_PHASE_INACTIVE)
			DriftTelemetryRow(car, ctrl, air ? "AIR" : "LAND");
		if(ctrl->m_fBoostLevel > state->fPrevBoost){
			char event[32];
			sprintf(event, "BOOST %.2f->%.2f", state->fPrevBoost, ctrl->m_fBoostLevel);
			DriftTelemetryRow(car, ctrl, event);
		}
		// A handbrake edge that was denied an entry names the first gate that
		// failed. The drift itself starts later in the same frame, so a gate
		// that passes records no deny here.
		if(handbrake && !state->bPrevHandbrake &&
		   ctrl->m_Phase == CDriftControl::DRIFT_PHASE_INACTIVE){
			float fwdSpeed = DotProduct(car->m_vecMoveSpeed, car->GetForward());
			if(air)
				DriftTelemetryRow(car, ctrl, "DENY:air");
			else if(fwdSpeed <= 0.0f)
				DriftTelemetryRow(car, ctrl, "DENY:rev");
			else if(Abs(car->m_fSteerInput) <= DRIFT_ENTRY_STEER)
				DriftTelemetryRow(car, ctrl, "DENY:steer");
		}
	}
	state->bFirstCall = false;

	// The live rows run while the drift is on or the handbrake is held, at
	// most every 50 ms of game time. An edge row above pushes the next live
	// row out by the same amount, so a single frame never writes two copies
	// of the same state.
	if((ctrl->m_Phase != CDriftControl::DRIFT_PHASE_INACTIVE || handbrake) &&
	   CTimer::GetTimeInMilliseconds() >= state->nNextRowMs)
		DriftTelemetryRow(car, ctrl, "");

	state->ePrevPhase = ctrl->m_Phase;
	state->bPrevAir = air;
	state->bPrevHandbrake = handbrake;
	state->fPrevBoost = ctrl->m_fBoostLevel;
}

void
CDriftTelemetry::Event(CAutomobile *car, CDriftControl *ctrl, const char *event)
{
	tDriftTelemetry *state;

	if(!gDriftDebug || car == nil || ctrl == nil)
		return;

	state = ms_pTelemetry;
	if(state == nil)
		state = DriftTelemetryInit(car, ctrl);
	if(state == nil)
		return;

	DriftTelemetryRow(car, ctrl, event != nil ? event : "");
}
